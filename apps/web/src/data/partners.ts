export function getPartnersForTournament(tournamentSlug: string): PartnerCandidate[] {
  const specific = PARTNER_CANDIDATES.filter((p) => p.tournamentSlug === tournamentSlug);
  if (specific.length > 0) return specific;
  // If specific is empty, return a subset of active Bengaluru partners so every tournament has pairs available
  return PARTNER_CANDIDATES.slice(0, 3);
}

export function getPartnerById(id: string): PartnerCandidate | undefined {
  return PARTNER_CANDIDATES.find((p) => p.id === id);
}

export function getAllPartners(): PartnerCandidate[] {
  return PARTNER_CANDIDATES;
}
